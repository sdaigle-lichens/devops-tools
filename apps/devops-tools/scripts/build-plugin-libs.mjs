#!/usr/bin/env node
// Regenerates the plugin's standalone board-schema lib from src/core.
//
// Why this exists: the init/update skills validate the board they just wrote, and they run inside
// the USER'S repository — under bare `node`, with no node_modules of ours and no install step. So
// the validator cannot import anything from this workspace, and it cannot `require("zod")`. The
// alternative to generating it is maintaining a second hand-written validator that drifts from
// the schema until the day a skill writes a board the app refuses to open.
//
//   pnpm --filter devops-tools build:plugin-libs
//
// The generated file is committed, because the plugin is consumed by file copy and has to be
// present in the repo rather than produced at install time. Zod is inlined into it; that is the
// price of one source of truth, and the reason the bundle is a few hundred kB rather than a few.
//
// THIS SCRIPT FAILS QUIETLY. If it stops producing correct output the committed .cjs keeps
// working and every test stays green; the symptom is that a schema change never reaches the
// skills, and boards get validated against last month's rules. After changing anything here or in
// board-schema.ts, re-run it and read `git diff plugins/devops-tools/scripts/lib/`.

import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const outDir = path.resolve(appRoot, "../../plugins/devops-tools/scripts/lib");

// esbuild stamps a `// <path>` comment above each bundled module, relative to its working
// directory — so the bundle's bytes depend on where the build was launched from. Pinned to the app
// root rather than left as process.cwd(), so running this from the repo root and running it
// through pnpm produce the same file instead of a spurious diff for whoever runs the other one.
const absWorkingDir = appRoot;

// Pinned rather than discovered: esbuild walks up from the entry point looking for a tsconfig, and
// `strict` in whichever one it finds is what makes it emit "use strict" at the top of a CJS
// bundle. tsconfig.json here is a solution file with no compilerOptions at all, so the walk would
// find nothing to be strict about. tsconfig.node.json is the project that actually owns src/core.
const tsconfig = path.join(appRoot, "tsconfig.node.json");

const BANNER = `// GENERATED by apps/devops-tools/scripts/build-plugin-libs.mjs — DO NOT EDIT.
// Source: apps/devops-tools/src/core/board-schema.ts
// Regenerate with: pnpm --filter devops-tools build:plugin-libs`;

const entries = [{ name: "board-schema", entry: "src/core/board-schema.ts" }];

for (const { name, entry } of entries) {
  await build({
    absWorkingDir,
    entryPoints: [entry],
    outfile: path.join(outDir, `${name}.cjs`),
    bundle: true,
    platform: "node",
    target: "node20",
    format: "cjs",
    tsconfig,
    banner: { js: BANNER },
    logLevel: "info",
  });
}
